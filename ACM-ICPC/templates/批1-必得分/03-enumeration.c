//   用 100 元买 100 只鸡：公鸡 5 元一只、母鸡 3 元一只、小鸡 1 元三只（必须整三只买）。
//   求所有买法，每行输出三个整数：公鸡数、母鸡数、小鸡数，按公鸡数从小到大排列（公鸡可以是 0 只）。
//   样例输出：
//     0 25 75
//     4 18 78
//     8 11 81
//     12 4 84
//
// 待填：枚举函数 + 最小可跑样例。现在只有题面与说明，没有任何代码。

#include <stdio.h>

int main(void) {
	int a,b,c;
	for (a=0;a<20;a++) {
		for (b=0;b<33;b++) {
			int t=7*a+4*b;
			int c=100-a-b;
			if (t==100) {
				printf("%d %d %d\n",a,b,c);
			}
		}
	}
	
	return 0;
}
