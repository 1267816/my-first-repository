#include <stdio.h>

int main(void)
{
    unsigned int x = 0x10;   /* 0x10 = 16 */
    unsigned int y = 0x02;

    printf("x = %u, y = %u\n", x, y);
    printf("x & y  = %u\n", x & y);   /* 与：两位都为 1 才是 1，这里没有重叠的位 */
    printf("x | y  = %u\n", x | y);   /* 或：把两边的 1 拼起来 */
    printf("~x     = %u\n", ~x);      /* 取反：每一位翻转；按无符号打印是一串很大的数 */
    printf("x ^ y  = %u\n", x ^ y);   /* 异或：两位不同才是 1 */
    printf("x << 2 = %u\n", x << 2);  /* 左移，右边补 0，相当于 × 2^2 */
    printf("x >> 2 = %u\n", x >> 2);  /* 右移；无符号数左边补 0 */

    /* 逻辑运算只看“是不是 0”，按位运算看每一位，所以结果完全不同 */
    printf("5 & 4  = %d\n", 5 & 4);    /* 按位与：101 & 100 = 100 = 4 */
    printf("5 && 4 = %d\n", 5 && 4);   /* 逻辑与：两个都非 0，结果是 1 */
    printf("5 | 4  = %d\n", 5 | 4);    /* 按位或：101 | 100 = 101 = 5 */
    printf("5 || 4 = %d\n", 5 || 4);   /* 逻辑或：结果也是 1 */
    printf("~4     = %d\n", ~4);       /* 按位取反：~x 等于 -x-1，所以是 -5（不是 3，也不是 5） */
    printf("!4     = %d\n", !4);       /* 逻辑非：4 非 0，取反得 0 */
    printf("~0     = %u\n", ~0);       /* 全部位为 1 */

    /* 常用的两种应用：把某些位清 0、把某些位置 1 */
    printf("12 把第 2 位清 0：%d\n", 12 & ~4);        /* 1100 & 1011 = 1000 = 8 */
    printf("8 把第 0 位置 1：%d\n", 8 | 0x01);         /* 1000 | 0001 = 1001 = 9 */
    printf("取 0x1234 的低 8 位：%d\n", 0x1234 & 0xFF); /* 0x34 = 52 */

    return 0;
}
