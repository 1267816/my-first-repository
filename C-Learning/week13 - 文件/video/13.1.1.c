// 13.1.1 格式化的输入输出
// AI 整理（DSH）：按课件与 note-13.1 整理，不是翁恺视频里的逐字原文，变量名、注释与演示顺序可能与课堂不同。
#include <stdio.h>

int main(void)
{
    int a, b;

    /* ---- flags：- 左对齐、+ 带符号、空格给正数留位、0 填充 ---- */
    printf("[%d]\n", 123);        /* [123] */
    printf("[%-6d]\n", 123);      /* 左对齐，右边补空格 */
    printf("[%+d]\n", 123);       /* 正数也带上 + */
    printf("[% d]\n", 123);       /* 正数前面留一个空格 */
    printf("[%06d]\n", 123);      /* 用 0 补齐到 6 位 */

    /* ---- width（最小宽度）和 precision（小数位数）---- */
    printf("[%6d]\n", 123);        /* 宽度 6，右对齐 */
    printf("[%6.2f]\n", 3.14159);  /* 宽度 6，小数点后 2 位 */

    /* ---- 星号：宽度、精度由后面的参数传进来，不写死在格式串里 ----
       下面两行分别等价于 printf("[%5d]") 和 printf("[%.2f]") ---- */
    printf("[%*d]\n", 5, 123);
    printf("[%.*f]\n", 2, 3.14159);

    /* ---- 类型修饰 hh：只取最低 8 位。300 = 0x12C，低 8 位是 0x2C = 44 ----
       但 MSVCRT（Dev-C++ 的 TDM-GCC）不认 hh，会把 300 原样打出来；
       本机 mingw64（UCRT）和 glibc 才会按 44 打。
       下面第二行用显式强转 (char)，哪种编译器都给 44，可以对照着看。 ---- */
    printf("[%hhd]\n", 300);
    printf("[%d]\n", (char)300);

    /* ---- scanf：* 表示跳过这一项，数字表示最多读几个字符 ----
       输入 1 2 3 时，2 被 %*d 读走丢掉，a 得 1、b 得 3。
       注意这里要写 %%：printf 的格式串里 %*d 本身是一个格式符，想原样打印出来得转义。 ---- */
    printf("输入 1 2 3：");
    scanf("%d %*d %d", &a, &b);
    printf("a=%d b=%d（中间的 2 被 %%*d 跳过了）\n", a, b);

    /* ---- %n：不输出内容，只把“到此刻已经打印了几个字符”存进指针 ----
       课件里的写法是：
           int num;
           printf("12345%n\n", &num);    // num 会变成 5
       但这段在这两套编译器上都演示不了，所以只留注释：
         - Dev-C++ 自带的 TDM-GCC 9.2（MSVCRT）：%n 默认被禁用，遇到 %n 就停止解析，
           连它后面的 \n 都不输出，num 不会被赋值；它也没有 _set_printf_count_output 可以打开。
         - 本机的 mingw64（UCRT）：要先调用 _set_printf_count_output(1) 才生效，否则一样被禁用。 */

    return 0;
}
